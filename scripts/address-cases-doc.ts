/**
 * Renders docs/ADDRESS_CASES.md from tests/fixtures/address-cases.json (written by scripts/record-address-cases.ts).
 * Run: npm run build && node dist/scripts/address-cases-doc.js   (offline). tests/address-cases.test.ts fails if the doc is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

interface Recorded { input: string; category: string; outcome: string; bin?: string; matched?: string; why: string }

const cell = (s: string) =>
  JSON.stringify(s)
    .slice(1, -1)
    .replace(/[\u0080-￿]/g, (ch) => `\\u${ch.charCodeAt(0).toString(16).padStart(4, "0")}`)
    .replace(/\|/g, "\\|")
    .replace(/\\"/g, '"');
const shorten = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 3)}...` : s);

export function renderAddressCases(cases: Recorded[]): string {
  const counts = new Map<string, number>();
  for (const c of cases) counts.set(c.outcome, (counts.get(c.outcome) ?? 0) + 1);
  const lines = [
    "# Address cases: outcome and reason for every input tried",
    "",
    "Generated by `scripts/address-cases-doc.ts` from `tests/fixtures/address-cases.json`, which `scripts/record-address-cases.ts`",
    "recorded live on 2026-11-03 through the real MCP server (`resolve_property`, GeoSearch's 10 closest candidates). The same",
    "recorded responses are replayed offline by `tests/address-cases.test.ts`, which must reproduce every outcome below.",
    "",
    "Rule: a wrong building must never come back as a success. Every `success` row below was checked by hand: the matched address",
    "is the one typed (same house number, street name and type, and the typed borough if any). Inputs are shown JSON-escaped",
    "(e.g. `\\u200b` is a zero-width space).",
    "",
    `Totals (${cases.length} inputs): ${[...counts].map(([k, v]) => `${k} ${v}`).join(", ")}.`,
    "",
    "Outcomes: `success` (one building returned); `place-only` (only a borough/city/zip; refused before any request);",
    "`invalid-input` (rejected by input validation, e.g. shorter than 5 characters); `mismatch` (no candidate matches what was",
    "typed; the error shows the closest one and its BIN); `ambiguous` (more than one building matches; all are listed, none used);",
    "`no-match` (GeoSearch returned nothing); `placeholder` (the only match has a borough-level placeholder BIN).",
    "",
    "| # | Category | Input | Outcome | Matched building / reason |",
    "|---|---|---|---|---|",
  ];
  cases.forEach((c, i) => {
    const detail = c.outcome === "success" ? `${c.matched}, BIN ${c.bin}` : c.why;
    lines.push(`| ${i + 1} | ${c.category} | \`${shorten(cell(c.input), 60)}\` | ${c.outcome} | ${cell(shorten(detail, 220))} |`);
  });
  return lines.join("\n") + "\n";
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const root = process.cwd();
  const cases = JSON.parse(readFileSync(join(root, "tests", "fixtures", "address-cases.json"), "utf8")) as Recorded[];
  writeFileSync(join(root, "docs", "ADDRESS_CASES.md"), renderAddressCases(cases));
  console.error(`wrote docs/ADDRESS_CASES.md (${cases.length} cases)`);
}
